import {
  ChangeDetectionStrategy,
  Component,
  computed,
  effect,
  inject,
  signal,
  untracked,
} from '@angular/core';
import { toSignal } from '@angular/core/rxjs-interop';
import { FormControl, FormGroup, ReactiveFormsModule } from '@angular/forms';
import { ActivatedRoute, Params, Router } from '@angular/router';
import { Observable, catchError, forkJoin, map, of } from 'rxjs';

import { toUserError } from '../../../core/errors/user-error';
import { requestState } from '../../../core/http/request-state';
import { AlcoFilterBar } from '../../../shared/filters/filter-bar';
import { AlcoAutocomplete, AutocompleteOption } from '../../../shared/forms/autocomplete';
import { AlcoFormField } from '../../../shared/forms/form-field';
import { AlcoInput } from '../../../shared/forms/input';
import { AlcoButton } from '../../../shared/ui/button/button';
import { AlcoEmptyState } from '../../../shared/ui/empty-state/empty-state';
import { AlcoErrorState } from '../../../shared/ui/error-state/error-state';
import { AlcoLoading } from '../../../shared/ui/loading/loading';
import { AlcoPageHeader } from '../../../shared/ui/page-header/page-header';
import { AlcoTabPanel, AlcoTabs, TabItem } from '../../../shared/ui/tabs/tabs';
import { PartnersApi } from '../../partners/data-access/partners-api';
import { AccountingApi } from '../data-access/accounting-api';
import { accountCodeSearch, codeOption, partnerCodeSearch } from '../data-access/code-searches';
import { DueItemStatus, DueRole } from '../data-access/due-models';
import { EntriesApi } from '../data-access/entries-api';
import { AlcoDueItems } from './due-items';
import { DUE_ERRORS, DUE_ROLES, DUE_STATUS, DUE_STATUSES } from './due-presentation';
import { DueScope } from './due-scope';
import { AlcoPendingLines } from './pending-lines';

/** The two views of the screen (`vue` of the URL; the installments when absent). */
type View = 'echeances' | 'a-generer';

const PARAM = {
  view: 'vue',
  partner: 'tiers',
  account: 'compte',
  role: 'role',
  state: 'etat',
  from: 'du',
  to: 'au',
  page: 'page',
} as const;
const VIEWS: readonly View[] = ['echeances', 'a-generer'];
const ROLES = Object.keys(DUE_ROLES) as DueRole[];
const ISO_DATE = /^\d{4}-\d{2}-\d{2}$/;

interface Found {
  readonly account: string | null | undefined;
  readonly partner: string | null | undefined;
}

/**
 * Comptabilité › Échéances (V2.1, lot A5), on the API: the installments the server computed
 * and settles (`due-items/`), and the invoices still without due dates (`pending-lines/`),
 * generated by the server's command. The partner and the account are filtered by code
 * (readable, shareable URL), found by the server first; view, role, state, dates and page
 * live in the URL too. Every date, amount and state is the server's.
 */
@Component({
  selector: 'alco-due-page',
  imports: [
    ReactiveFormsModule,
    AlcoButton,
    AlcoDueItems,
    AlcoEmptyState,
    AlcoErrorState,
    AlcoFilterBar,
    AlcoAutocomplete,
    AlcoFormField,
    AlcoInput,
    AlcoLoading,
    AlcoPageHeader,
    AlcoPendingLines,
    AlcoTabPanel,
    AlcoTabs,
  ],
  templateUrl: './due-page.html',
  styleUrls: ['../accounting-list.scss', './due-page.scss'],
  changeDetection: ChangeDetectionStrategy.OnPush,
})
export class DuePage {
  private readonly accounting = inject(AccountingApi);
  private readonly entries = inject(EntriesApi);
  protected readonly searchAccounts = accountCodeSearch(this.accounting);
  protected readonly searchPartners = partnerCodeSearch(this.entries);
  private readonly router = inject(Router);
  private readonly route = inject(ActivatedRoute);

  protected readonly tabs: readonly TabItem[] = [
    { id: 'echeances', label: 'Échéances' },
    { id: 'a-generer', label: 'Échéances à générer' },
  ];
  protected readonly roles = ROLES.map((id) => ({ id, label: DUE_ROLES[id] }));
  protected readonly statuses = DUE_STATUSES.map((id) => ({ id, label: DUE_STATUS[id].label }));

  private readonly params = toSignal(this.route.queryParamMap, {
    initialValue: this.route.snapshot.queryParamMap,
  });
  private readonly param = (name: string) => this.params().get(name)?.trim() || null;
  protected readonly view = computed<View>(() => {
    const value = this.param(PARAM.view);
    return VIEWS.includes(value as View) ? (value as View) : 'echeances';
  });
  protected readonly partnerCode = computed(() => this.param(PARAM.partner));
  protected readonly accountCode = computed(() => this.param(PARAM.account));
  protected readonly role = computed<DueRole | null>(() => {
    const value = this.param(PARAM.role);
    return ROLES.includes(value as DueRole) ? (value as DueRole) : null;
  });
  protected readonly status = computed<DueItemStatus | null>(() => {
    const value = this.param(PARAM.state);
    return DUE_STATUSES.includes(value as DueItemStatus) ? (value as DueItemStatus) : null;
  });
  protected readonly dateFrom = computed(() => this.date(PARAM.from));
  protected readonly dateTo = computed(() => this.date(PARAM.to));
  protected readonly page = computed(() => Math.max(1, Number(this.params().get(PARAM.page)) || 1));

  protected readonly activeFilterCount = computed(
    () =>
      [
        this.partnerCode(),
        this.accountCode(),
        this.role(),
        this.view() === 'echeances' ? this.status() : null,
        this.dateFrom() || this.dateTo(),
      ].filter(Boolean).length,
  );

  private readonly codes = computed(() => ({
    account: this.accountCode(),
    partner: this.partnerCode(),
  }));
  protected readonly found = requestState(() => this.find(untracked(this.codes)), {
    immediate: false,
  });
  protected readonly findFailure = computed(() => {
    const error = this.found.error();
    return error ? toUserError(error, DUE_ERRORS) : null;
  });
  protected readonly unknownCode = computed(() => {
    const found = this.found.value();
    if (found?.account === null) {
      return `Aucun compte de cette société n’a le code « ${this.accountCode()} ».`;
    }
    if (found?.partner === null) {
      return `Aucun tiers de cette société n’a le code « ${this.partnerCode()} ».`;
    }
    return null;
  });
  protected readonly scope = computed<DueScope | null>(() => {
    const found = this.found.value();
    if (!found || this.found.loading() || this.unknownCode()) {
      return null;
    }
    return {
      partner: found.partner ?? null,
      account: found.account ?? null,
      role: this.role(),
      status: this.status(),
      dateFrom: this.dateFrom(),
      dateTo: this.dateTo(),
      page: this.page(),
    };
  });

  protected readonly decimals = signal<ReadonlyMap<string, number>>(new Map());

  protected readonly filterForm = new FormGroup({
    partner: new FormControl<AutocompleteOption | null>(null),
    account: new FormControl<AutocompleteOption | null>(null),
    role: new FormControl('', { nonNullable: true }),
    status: new FormControl('', { nonNullable: true }),
    dateFrom: new FormControl('', { nonNullable: true }),
    dateTo: new FormControl('', { nonNullable: true }),
  });

  constructor() {
    inject(PartnersApi)
      .currencies()
      .pipe(
        map((page) => new Map(page.results.map((item) => [item.code, item.decimal_places]))),
        catchError(() => of(new Map<string, number>())),
      )
      .subscribe((decimals) => this.decimals.set(decimals));
    effect(() => {
      this.codes();
      untracked(() => this.found.reload());
    });
    effect(() => {
      this.filterForm.setValue({
        partner: codeOption(this.partnerCode()),
        account: codeOption(this.accountCode()),
        role: this.role() ?? '',
        status: this.status() ?? '',
        dateFrom: this.dateFrom() ?? '',
        dateTo: this.dateTo() ?? '',
      });
    });
  }

  protected setView(view: string): void {
    if (view === this.view()) {
      return;
    }
    // Another list: its own state and page; the partner, account, role and dates stay.
    this.navigate({
      [PARAM.view]: view === 'echeances' ? null : view,
      [PARAM.state]: null,
      [PARAM.page]: null,
    });
  }

  protected applyFilters(): void {
    const value = this.filterForm.getRawValue();
    this.navigate({
      [PARAM.partner]: value.partner?.id ?? null,
      [PARAM.account]: value.account?.id ?? null,
      [PARAM.role]: value.role || null,
      [PARAM.state]: this.view() === 'echeances' ? value.status || null : null,
      [PARAM.from]: value.dateFrom || null,
      [PARAM.to]: value.dateTo || null,
      [PARAM.page]: null,
    });
  }

  protected resetFilters(): void {
    this.navigate(
      Object.fromEntries(
        Object.values(PARAM)
          .filter((name) => name !== PARAM.view)
          .map((name) => [name, null]),
      ),
    );
  }

  protected setPage(page: number): void {
    this.navigate({ [PARAM.page]: page > 1 ? page : null });
  }

  protected firstPage(): void {
    this.navigate({ [PARAM.page]: null }, true);
  }

  private find(codes: { account: string | null; partner: string | null }): Observable<Found> {
    const account = codes.account
      ? this.accounting.accountByCode(codes.account).pipe(map((found) => found?.public_id ?? null))
      : of(undefined);
    const partner = codes.partner
      ? this.entries.partnerByCode(codes.partner).pipe(map((found) => found?.public_id ?? null))
      : of(undefined);
    return forkJoin({ account, partner });
  }

  private date(name: string): string | null {
    const value = this.param(name);
    return value && ISO_DATE.test(value) ? value : null;
  }

  private navigate(params: Params, replaceUrl = false): void {
    void this.router.navigate([], {
      relativeTo: this.route,
      queryParams: params,
      queryParamsHandling: 'merge',
      replaceUrl,
    });
  }
}
