import { Component, signal } from '@angular/core';
import { TestBed } from '@angular/core/testing';

import { clearCookie, httpMock, provideHttpTesting, setCookie } from '../../core/http/testing';
import { SessionStore } from '../../core/session/session.store';
import { openTestSession } from '../../core/session/testing';
import { AlcoConfirmService } from '../../shared/ui/confirm-dialog/confirm-dialog';
import { AlcoToastService } from '../../shared/ui/toast/toast.service';
import { PARTNER_TRANSFER } from '../partners/partner-presentation';
import { AlcoDomainTransfers } from './domain-transfers';

@Component({
  imports: [AlcoDomainTransfers],
  template: `<alco-domain-transfers
    [transfer]="transfer"
    [exportParameters]="parameters()"
    exportScope="clients actifs"
  />`,
})
class Host {
  readonly transfer = PARTNER_TRANSFER;
  readonly parameters = signal({ role: 'customer', status: 'active' });
}

const settle = () => new Promise((resolve) => setTimeout(resolve, 0));

describe('AlcoDomainTransfers (« Actions ▾ » of a domain, real API)', () => {
  async function render(permissions: string[]) {
    TestBed.configureTestingModule({ providers: provideHttpTesting() });
    openTestSession(TestBed.inject(SessionStore), { permissions });
    setCookie('XSRF-TOKEN', 'tok');
    const fixture = TestBed.createComponent(Host);
    await fixture.whenStable();
    const element = fixture.nativeElement as HTMLElement;
    const open = async () => {
      element.querySelector<HTMLButtonElement>('button')?.click();
      await fixture.whenStable();
      return Array.from(document.querySelectorAll<HTMLElement>('[role=menuitem]'));
    };
    return { fixture, element, open };
  }

  afterEach(() => {
    httpMock().verify();
    clearCookie('XSRF-TOKEN');
    document.querySelectorAll('.cdk-overlay-container').forEach((node) => node.remove());
  });

  it('shows each operation only with its two permissions', async () => {
    const reader = await render(['partners.read']);
    expect(reader.element.querySelector('button')).toBeNull();
    TestBed.resetTestingModule();

    const exporter = await render(['partners.read', 'imports_exports.export']);
    expect((await exporter.open()).map((item) => item.textContent?.trim())).toEqual([
      'Exporter les contacts',
    ]);
    TestBed.resetTestingModule();

    const importer = await render(['partners.create', 'imports_exports.create']);
    expect((await importer.open()).map((item) => item.textContent?.trim())).toEqual([
      'Importer des contacts',
    ]);
  });

  it('export: confirmed, generated by the server with the list criteria, then downloaded', async () => {
    const { fixture, open } = await render(['partners.read', 'imports_exports.export']);
    const confirm = vi.spyOn(TestBed.inject(AlcoConfirmService), 'confirm').mockResolvedValue(true);
    const createUrl = vi.fn(() => 'blob:tiers');
    Object.assign(URL, { createObjectURL: createUrl, revokeObjectURL: vi.fn() });
    const clicked = vi
      .spyOn(HTMLAnchorElement.prototype, 'click')
      .mockImplementation(() => undefined);

    (await open())[0].click();
    await settle();
    expect(confirm).toHaveBeenCalledWith(
      expect.objectContaining({
        title: 'Exporter les contacts ?',
        confirmLabel: 'Exporter les contacts',
      }),
    );
    const create = httpMock().expectOne('/api/v1/imports-exports/exports/');
    expect(create.request.body).toEqual({
      export_type: 'partners',
      // CSV unless a format is asked (the reports' PDF / XLSX exports ask theirs).
      file_format: 'csv',
      parameters: { role: 'customer', status: 'active' },
      asynchronous: false,
    });
    create.flush({
      public_id: 'e1',
      export_type: 'partners',
      status: 'completed',
      filename: 'partners.csv',
      row_count: 12,
      error: {},
    });
    await settle();
    httpMock()
      .expectOne('/api/v1/imports-exports/exports/e1/download/')
      .flush(new Blob(['code\n']), {
        headers: { 'Content-Disposition': 'attachment; filename="tiers.csv"' },
      });
    await settle();
    await fixture.whenStable();
    expect(createUrl).toHaveBeenCalled();
    expect(clicked).toHaveBeenCalled();
    expect(TestBed.inject(AlcoToastService).toasts()[0]?.message).toBe('Export prêt : 12 lignes.');
  });

  it('a failed export is said, nothing is downloaded', async () => {
    const { open } = await render(['partners.read', 'imports_exports.export']);
    vi.spyOn(TestBed.inject(AlcoConfirmService), 'confirm').mockResolvedValue(true);
    (await open())[0].click();
    await settle();
    httpMock()
      .expectOne('/api/v1/imports-exports/exports/')
      .flush({ public_id: 'e1', status: 'failed', filename: '', row_count: null, error: {} });
    await settle();
    httpMock().expectNone('/api/v1/imports-exports/exports/e1/download/');
    expect(TestBed.inject(AlcoToastService).toasts()[0]?.tone).toBe('danger');
  });
});
