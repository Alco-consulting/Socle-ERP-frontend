import { ChangeDetectionStrategy, Component, computed, inject, input, signal } from '@angular/core';
import { ActivatedRoute, Router } from '@angular/router';
import { firstValueFrom } from 'rxjs';

import { toUserError } from '../../core/errors/user-error';
import { toApiError } from '../../core/http/api-error';
import { SessionStore } from '../../core/session/session.store';
import { AlcoConfirmService } from '../../shared/ui/confirm-dialog/confirm-dialog';
import { AlcoDropdown, DropdownItem } from '../../shared/ui/dropdown/dropdown';
import { AlcoToastService } from '../../shared/ui/toast/toast.service';
import { saveFile } from '../../shared/utils/save-file';
import { ContextualTransfer } from './contextual-transfer';
import { TRANSFER_ERRORS } from './transfer-messages';
import { TransfersApi } from './transfers-api';

/**
 * « Actions ▾ » of a domain list with ITS import and export, on the real API. Each entry
 * needs the `imports_exports.*` permission and the domain's own; without them it is not
 * shown. The export is generated by the server (synchronously), then downloaded with the
 * session: the file never goes through a public link.
 */
@Component({
  selector: 'alco-domain-transfers',
  imports: [AlcoDropdown],
  template: `
    @if (items().length > 0) {
      <alco-dropdown align="end" [items]="items()" (selected)="onSelected($event)">
        {{ exporting() ? 'Export en cours…' : 'Actions' }}
      </alco-dropdown>
    }
  `,
  changeDetection: ChangeDetectionStrategy.OnPush,
})
export class AlcoDomainTransfers {
  private readonly session = inject(SessionStore);
  private readonly api = inject(TransfersApi);
  private readonly router = inject(Router);
  private readonly route = inject(ActivatedRoute);
  private readonly confirm = inject(AlcoConfirmService);
  private readonly toast = inject(AlcoToastService);

  readonly transfer = input.required<ContextualTransfer>();
  /** Criteria of the list the export follows (only those the export type accepts). */
  readonly exportParameters = input<Readonly<Record<string, string>>>({});
  /** Words for the confirmation: « tous les tiers actifs ». */
  readonly exportScope = input('');
  /** Import screen, relative to the current one. */
  readonly importPath = input('import');

  protected readonly exporting = signal(false);

  protected readonly items = computed<readonly DropdownItem[]>(() => {
    const transfer = this.transfer();
    const items: DropdownItem[] = [];
    if (
      transfer.importType &&
      this.session.can('imports_exports.create') &&
      this.session.can(transfer.importPermission)
    ) {
      items.push({ id: 'import', label: transfer.importLabel, icon: 'upload' });
    }
    if (
      transfer.exportType &&
      this.session.can('imports_exports.export') &&
      this.session.can(transfer.exportPermission)
    ) {
      items.push({
        id: 'export',
        label: transfer.exportLabel,
        icon: 'download',
        disabled: this.exporting(),
      });
    }
    return items;
  });

  protected async onSelected(item: DropdownItem): Promise<void> {
    if (item.id === 'import') {
      await this.router.navigate([this.importPath()], { relativeTo: this.route });
      return;
    }
    await this.export();
  }

  private async export(): Promise<void> {
    const transfer = this.transfer();
    if (!transfer.exportType || this.exporting()) {
      return;
    }
    const confirmed = await this.confirm.confirm({
      title: `${transfer.exportLabel} ?`,
      message:
        `Le serveur prépare un fichier CSV${this.exportScope() ? ` de ${this.exportScope()}` : ''}, ` +
        'puis votre navigateur le télécharge. Le fichier reste privé et expire après un délai fixé par le serveur.',
      confirmLabel: transfer.exportLabel,
    });
    if (!confirmed) {
      return;
    }
    this.exporting.set(true);
    try {
      const run = await firstValueFrom(
        this.api.createExport(transfer.exportType, this.exportParameters()),
      );
      if (run.status !== 'completed') {
        this.toast.error(
          'L’export a échoué. Réessayez ; si le problème continue, contactez le support.',
        );
        return;
      }
      const file = await firstValueFrom(this.api.download(run.public_id));
      saveFile(file.blob, file.filename ?? run.filename ?? 'export.csv');
      const rows = run.row_count ?? 0;
      this.toast.success(`Export prêt : ${rows} ligne${rows > 1 ? 's' : ''}.`);
    } catch (failure) {
      const error = toApiError(failure);
      if (error.kind !== 'unauthenticated') {
        const text = toUserError(error, TRANSFER_ERRORS);
        this.toast.error(`${text.title} ${text.message}`);
      }
    } finally {
      this.exporting.set(false);
    }
  }
}
