import { Injectable, inject } from '@angular/core';
import { Observable, map } from 'rxjs';

import { ApiClient, Paginated } from '../../../core/http/api-client';
import { PartnerSummary } from '../../partners/data-access/partner-models';
import {
  Invoice,
  InvoiceQuery,
  InvoiceSummary,
  InvoiceUpdate,
  InvoiceWrite,
  Preview,
  PreviewRequest,
  Product,
  ProductQuery,
  ProductWrite,
} from './invoicing-models';

export const PRODUCT_PAGE_SIZE = 50;
export const INVOICE_PAGE_SIZE = 25;
/** A selection list of products: the server's largest page. */
const OPTIONS_PAGE_SIZE = 200;

const base = 'invoicing/';
const id = (value: string) => encodeURIComponent(value);

/**
 * Products and invoices on the API (note backend 0038), company scoped by the interceptor.
 * The server computes every amount, numbers the documents and generates their entries: the
 * screens send what is typed and show what it answers.
 */
@Injectable({ providedIn: 'root' })
export class InvoicingApi {
  private readonly api = inject(ApiClient);

  products(query: ProductQuery = {}): Observable<Paginated<Product>> {
    return this.api.get<Paginated<Product>>(`${base}products/`, {
      params: {
        search: query.search || null,
        status: query.status ?? null,
        page: query.page && query.page > 1 ? query.page : null,
        page_size: PRODUCT_PAGE_SIZE,
      },
    });
  }

  /** The active products of a selection list (first page of 200, by name). */
  productOptions(): Observable<Paginated<Product>> {
    return this.api.get<Paginated<Product>>(`${base}products/`, {
      params: { status: 'active', page_size: OPTIONS_PAGE_SIZE },
    });
  }

  product(productId: string): Observable<Product> {
    return this.api.get<Product>(`${base}products/${id(productId)}/`);
  }

  createProduct(product: ProductWrite): Observable<Product> {
    return this.api.post<Product>(`${base}products/`, product);
  }

  updateProduct(productId: string, changes: Partial<ProductWrite>): Observable<Product> {
    return this.api.patch<Product>(`${base}products/${id(productId)}/`, changes);
  }

  /** « Actif »: a command, never the form. */
  setProductActive(productId: string, active: boolean): Observable<Product> {
    const command = active ? 'reactivate' : 'deactivate';
    return this.api.post<Product>(`${base}products/${id(productId)}/${command}/`);
  }

  /** The active partners a document may name (« Client » and « Fournisseur » are labels). */
  partners(search: string): Observable<readonly PartnerSummary[]> {
    return this.api
      .get<Paginated<PartnerSummary>>('partners/', {
        params: { search: search || null, status: 'active', page_size: 20 },
      })
      .pipe(map((page) => page.results));
  }

  invoices(query: InvoiceQuery): Observable<Paginated<InvoiceSummary>> {
    return this.api.get<Paginated<InvoiceSummary>>(`${base}invoices/`, {
      params: {
        kind: query.kind,
        status: query.status ?? null,
        search: query.search || null,
        page: query.page && query.page > 1 ? query.page : null,
        page_size: INVOICE_PAGE_SIZE,
      },
    });
  }

  invoice(invoiceId: string): Observable<Invoice> {
    return this.api.get<Invoice>(`${base}invoices/${id(invoiceId)}/`);
  }

  createInvoice(invoice: InvoiceWrite): Observable<Invoice> {
    return this.api.post<Invoice>(`${base}invoices/`, invoice);
  }

  updateInvoice(invoiceId: string, changes: InvoiceUpdate): Observable<Invoice> {
    return this.api.patch<Invoice>(`${base}invoices/${id(invoiceId)}/`, changes);
  }

  deleteInvoice(invoiceId: string): Observable<void> {
    return this.api.delete<void>(`${base}invoices/${id(invoiceId)}/`);
  }

  /** The amounts of a draft as typed, and its entry to come (note backend 0041). */
  preview(request: PreviewRequest): Observable<Preview> {
    return this.api.post<Preview>(`${base}invoices/preview/`, request);
  }

  /** « Comptabiliser »: the number and the entry, generated by the server. */
  post(invoiceId: string): Observable<Invoice> {
    return this.api.post<Invoice>(`${base}invoices/${id(invoiceId)}/post/`);
  }

  /** « Remettre en brouillon » (note backend 0040): its entry reversed, its number kept. */
  resetToDraft(invoiceId: string): Observable<Invoice> {
    return this.api.post<Invoice>(`${base}invoices/${id(invoiceId)}/reset-to-draft/`);
  }

  cancel(invoiceId: string, reason: string): Observable<Invoice> {
    return this.api.post<Invoice>(`${base}invoices/${id(invoiceId)}/cancel/`, { reason });
  }

  /** A draft credit note of a posted invoice, its lines copied. */
  creditNote(invoiceId: string): Observable<Invoice> {
    return this.api.post<Invoice>(`${base}invoices/${id(invoiceId)}/credit-note/`, {});
  }
}
